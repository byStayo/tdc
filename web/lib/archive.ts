import archiveContent from './archive-content.json';

export type ArchiveInline =
  | { type: 'text'; text: string }
  | { type: 'break' }
  | { type: 'strong' | 'em' | 'code'; children: ArchiveInline[] }
  | { type: 'link'; href: string; children: ArchiveInline[] };

export type ArchiveBlock =
  | { type: 'paragraph'; children: ArchiveInline[] }
  | { type: 'heading'; level: 2 | 3 | 4; children: ArchiveInline[] }
  | { type: 'quote'; blocks: ArchiveBlock[] }
  | { type: 'list'; ordered: boolean; items: ArchiveBlock[][] }
  | { type: 'image'; src: string; sourceUrl: string; mediaStatus: 'local' | 'external'; alt: string; caption: ArchiveInline[]; width?: number; height?: number }
  | { type: 'rule' };

export type ArchiveArticle = {
  id: string;
  title: string;
  excerpt: string;
  sourceUrl: string;
  publishedAt: string;
  author: string;
  publisher: 'WordPress' | 'Substack';
  readingMinutes: number;
  blocks: ArchiveBlock[];
};

// Generated by scripts/import-archive.py from the recovered public article bodies.
// It emits an allowlisted content tree, never source HTML or arbitrary attributes.
const articles = archiveContent as ArchiveArticle[];
const byId = new Map(articles.map((article) => [article.id, article]));

export function archiveArticles(): readonly ArchiveArticle[] {
  return articles;
}

export function archiveArticle(id: string): ArchiveArticle | undefined {
  return byId.get(id);
}

export function archivePath(id: string): string {
  return `/research/${encodeURIComponent(id)}`;
}

export function archiveDate(publishedAt: string): string {
  return new Intl.DateTimeFormat('en-US', {
    month: 'long', day: 'numeric', year: 'numeric', timeZone: 'UTC',
  }).format(new Date(publishedAt));
}

export function relatedArchiveArticles(article: ArchiveArticle): ArchiveArticle[] {
  const samePublication = articles.filter((item) => item.publisher === article.publisher);
  const position = samePublication.findIndex((item) => item.id === article.id);
  return [...samePublication.slice(position + 1), ...samePublication.slice(0, position)]
    .slice(0, 3);
}

export function safeArchiveUrl(value: string): string | undefined {
  try {
    const url = new URL(value);
    if (!['https:', 'http:'].includes(url.protocol) || url.username || url.password) return undefined;
    return url.href;
  } catch {
    return undefined;
  }
}

export function safeArchiveMediaUrl(value: string): string | undefined {
  if (/^\/archive-media\/[a-f0-9]{64}\.(?:png|jpg|webp|gif|avif)$/.test(value)) return value;
  return safeArchiveUrl(value);
}

export function localArchiveLink(sourceUrl: string): string | undefined {
  const safe = safeArchiveUrl(sourceUrl);
  if (!safe) return undefined;
  const target = new URL(safe);
  const article = articles.find((item) => {
    const original = new URL(item.sourceUrl);
    return original.hostname === target.hostname && original.pathname.replace(/\/$/, '') === target.pathname.replace(/\/$/, '');
  });
  return article ? `${archivePath(article.id)}${target.hash}` : undefined;
}
